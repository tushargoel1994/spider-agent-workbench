"""
Output guardrails for text-to-sql agent
Validates the output generated by AI
"""

import sqlite3
from pathlib import Path

import sqlglot
from spider_agent_workbench.executor import execute_query
from spider_agent_workbench.guardrails.guardrail_result import GuardrailResult
from spider_agent_workbench.guardrails.sql_guardrails import validate_sql


def check_output_valid_sql(db_id: str, db_dir: Path, agent_output: str) -> GuardrailResult:
    """Check if the AI output is a valid, safe, executable sql query."""
    if agent_output is None or agent_output.strip() == "":
        return GuardrailResult(ok=False, reason="No final SQL was submitted")

    try:
        sqlglot.parse_one(agent_output, read="sqlite")
    except sqlglot.errors.ParseError as e:
        return GuardrailResult(ok=False, reason=f"Rejected: SQL failed to parse: {e}")

    guardrail_result = validate_sql(db_id, agent_output, db_dir)
    if not guardrail_result.ok:
        return guardrail_result

    try:
        execute_query(db_id, agent_output, db_dir, max_rows=5)
    except sqlite3.Error as e:
        return GuardrailResult(ok=False, reason=f"Rejected: SQL failed to execute: {e}")

    return GuardrailResult(ok=True)


def run_output_guardrails(db_id: str, db_dir: Path, agent_output: str) -> GuardrailResult:
    """Common method to call output guardrails"""
    return check_output_valid_sql(db_id, db_dir, agent_output)

